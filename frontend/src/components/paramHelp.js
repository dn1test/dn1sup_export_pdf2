// Источники, значение которых пользователь заполняет сам: пустое поле не печатается
const FILLED_BY_USER = new Set([
  "project.articul", "project.address", "project.materials", "project.lighting",
  "customer.id", "customer.name", "customer.phone", "customer.email",
  "workflow.author", "workflow.rate", "workflow.status",
])
const USER_FILL_NOTE = " Если поле не заполнено, параметр не печатается."

const DIR_HELP = {
  line: "Раздел спецификации: название папки печатается первой строкой, её описание — следующей.",
  title: "Название раздела спецификации (заголовок папки).",
  description: "Описание раздела спецификации (описание папки).",
}

export function paramHelpTitle(p) {
  if (!p) return ""
  if (p.group) {
    return p.direction === "vertical"
      ? "Блок объединяет параметры в столбец: каждый параметр печатается на своей строке. Перетащите параметры на блок мышкой, крестик у параметра выводит его из блока."
      : "Блок объединяет параметры в одну строку: значения печатаются через « | ». Перетащите параметры на блок мышкой, крестик у параметра выводит его из блока."
  }
  const s = String(p.source || "")
  const dir = s.match(/^dir\.(\d+)\.(title|description|line)$/)
  if (dir) return DIR_HELP[dir[2]] || ""
  const text = PARAM_HELP[s]
  if (!text) return "Значение подставляется автоматически из данных проекта."
  return FILLED_BY_USER.has(s) ? text + USER_FILL_NOTE : text
}
